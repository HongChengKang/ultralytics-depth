"""detdist training entry: YOLO26n + one distance channel per level, trained from scratch.

三条约定（避免"参数藏在别处"）：
  1. 唯一可改的默认值表在下面的 ``DEFAULTS``（imgsz / project / name / batch ... 都在这）；
  2. ``configs/detdist_train.yaml`` 覆盖 DEFAULTS；
  3. 命令行 ``--key value`` 或 ``key=value`` 覆盖前两者。
启动时打印 "effective training settings" 表，逐项标出来源（DEFAULTS / yaml / CLI）。

实现来自 ``hzh_workspace/libs/detdist``（检测头注入，仓库源码未改）。数据集路径只在
``configs/detdist_dataset.yaml`` 的 ``dataset_root`` 一行里定义。

Usage
-----
  ./train_detdist.sh start                      # 默认配置，后台训练
  ./train_detdist.sh start --epochs 50 --name dbg
  tools/train/train_detdist.py --dry-run        # 只打印最终生效参数，不训练
  DETDIST_LAMBDA=0 tools/train/train_detdist.py --name det_only   # 检测-only baseline

Environment honoured by libs/detdist/:
  DETDIST_LAMBDA        weight of L_dist (default 0.5; 0 disables the distance loss)
  DETDIST_HUBER_DELTA   Huber delta on d_norm (default 0.1 == 1.5 m)
  DETDIST_LABELS_ROOT   override of labels_root (default /mnt/data2/hzh/PF_11.9/labels_dist)
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve()          # .../hzh_workspace/tools/train/train_detdist.py
WS = HERE.parents[2]                     # .../hzh_workspace
REPO = HERE.parents[3]                   # .../ultralytics-depth
sys.path[:0] = [str(WS / "libs"), str(REPO)]

# ---------------------------------------------------------------------------
# 训练默认值（想换 run 名/尺寸，改这里；imgsz 顺序是 (H, W)）
# 备注：model/data 是相对 hzh_workspace/ 的路径；project 相对 hzh_workspace/，
# 最终产物落在 <hzh_workspace>/<project>/<name>/。
# ---------------------------------------------------------------------------
DEFAULTS = {
    "model": "configs/detdist_model.yaml",
    "data": "configs/detdist_data.yaml",   # generated by tools/data/make_data_yaml.py
    "labels_root": "",                     # "" -> <dataset_root>/labels_dist
    "project": "runs",
    "name": "detdist_pf",
    "epochs": 400,
    "imgsz": 640,  # (H, W)；与 COCO_PF 参考配方一致
    "batch": 96,
    "device": "0",
    "workers": 8,
    "optimizer": "auto",
    "lr0": 0.001,
    "lrf": 0.01,
    "warmup_epochs": 3.0,
    "patience": 30,
    "seed": 0,
    "deterministic": True,
    "cache": False,
    "cos_lr": False,
    "close_mosaic": 10,
    "translate": 0.1,
    "scale": 0.5,
    "fliplr": 0.5,
    "flipud": 0.0,
    "hsv_h": 0.015,
    "hsv_s": 0.7,
    "hsv_v": 0.4,
    "erasing": 0.4,
    "dist_lambda": 0.5,
    "dist_huber_delta": 0.1,
    "exist_ok": False,
    "plots": True,
}


def _smart(v: str):
    """Convert a CLI string to bool/int/float/list/dict using YAML rules."""
    try:
        return yaml.safe_load(v)
    except Exception:  # noqa: BLE001 - plain string fallback
        return v


def _parse(argv: list[str]) -> dict:
    out: dict = {}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith("--"):
            if "=" in a:
                k, v = a[2:].split("=", 1)
            else:
                if i + 1 >= len(argv):
                    raise SystemExit(f"missing value for {a}")
                k, v = a[2:], argv[i + 1]
                i += 1
        elif "=" in a:
            k, v = a.split("=", 1)
        else:
            raise SystemExit(f"unrecognised argument: {a!r} (use --key value or key=value)")
        out[k.replace("-", "_")] = _smart(v)
        i += 1
    return out


def _dataset_root() -> str:
    """Read the single source of truth for the dataset location."""
    cfg = WS / "configs" / "detdist_dataset.yaml"
    if cfg.is_file():
        root = (yaml.safe_load(cfg.read_text()) or {}).get("dataset_root")
        if root:
            return str(root)
    return "/mnt/data2/hzh/PF_11.9"


def _fmt_imgsz(v) -> str:
    if isinstance(v, (list, tuple)):
        return "x".join(str(int(x)) for x in v) + "  (H,W)"
    return f"{int(v)}  (square)"


def main() -> None:
    argv = list(sys.argv[1:])
    dry = "--dry-run" in argv
    argv = [a for a in argv if a != "--dry-run"]

    # --config <file> : 先摘出来，再做两轮覆盖
    cfg_path = WS / "configs" / "detdist_train.yaml"
    if "--config" in argv:
        j = argv.index("--config")
        cfg_path = Path(argv[j + 1])
        del argv[j : j + 2]

    src = {k: "DEFAULTS" for k in DEFAULTS}
    cfg = dict(DEFAULTS)
    if cfg_path.is_file():
        for k, v in (yaml.safe_load(cfg_path.read_text()) or {}).items():
            cfg[k] = v
            src[k] = cfg_path.name
    else:
        print(f"[detdist] WARN config not found: {cfg_path} -> script DEFAULTS only", flush=True)

    for k, v in _parse(argv).items():
        cfg[k] = v
        src[k] = "CLI"

    os.environ["DETDIST_LAMBDA"] = str(cfg.get("dist_lambda", 0.5))
    os.environ["DETDIST_HUBER_DELTA"] = str(cfg.get("dist_huber_delta", 0.1))
    labels_root = str(
        cfg.get("labels_root")
        or os.environ.get("DETDIST_LABELS_ROOT")
        or os.environ.get("DIST_LABELS_ROOT")
        or (Path(_dataset_root()) / "labels_dist")
    )
    os.environ["DETDIST_LABELS_ROOT"] = labels_root
    if not cfg.get("labels_root"):
        cfg["labels_root"] = labels_root
        src["labels_root"] = "derived (<dataset_root>/labels_dist)"

    def _abs(key: str) -> Path:
        p = Path(str(cfg[key]))
        return p if p.is_absolute() else (WS / p)

    model_yaml = _abs("model")
    data_yaml = _abs("data")
    project = _abs("project")
    run_dir = project / str(cfg["name"])
    imgsz = tuple(cfg["imgsz"]) if isinstance(cfg["imgsz"], (list, tuple)) else int(cfg["imgsz"])

    show = [
        "model", "data", "labels_root", "project", "name", "epochs", "imgsz", "batch",
        "device", "workers", "optimizer", "lr0", "lrf", "warmup_epochs", "patience",
        "seed", "deterministic", "cache", "cos_lr", "close_mosaic", "translate", "scale",
        "fliplr", "flipud", "hsv_h", "hsv_s", "hsv_v", "erasing",
        "dist_lambda", "dist_huber_delta", "exist_ok", "plots",
    ]
    print("=" * 100, flush=True)
    print("[detdist] effective training settings   (source: DEFAULTS < yaml < CLI)", flush=True)
    print("-" * 100, flush=True)
    for k in show:
        v = cfg.get(k, DEFAULTS.get(k))
        if k == "imgsz":
            v = _fmt_imgsz(v)
        print(f"  {k:<16}: {str(v):<52} <- {src.get(k, 'DEFAULTS')}", flush=True)
    print("-" * 100, flush=True)
    print(f"  {'model (abs)':<16}: {model_yaml}", flush=True)
    print(f"  {'data  (abs)':<16}: {data_yaml}", flush=True)
    print(f"  {'run dir':<16}: {run_dir}   (project={project}, name={cfg['name']})", flush=True)
    print(f"  {'imgsz meaning':<16}: H x W used for train+val; "
          f"ONNX export must use the same size", flush=True)
    print("=" * 100, flush=True)

    if dry:
        print("[detdist] --dry-run: 只打印参数，不加载模型、不训练", flush=True)
        return

    # imported after sys.path is ready; they must see the env vars above
    from ultralytics import YOLO  # noqa: E402

    from detdist.trainer import DistTrainer  # noqa: E402

    DistTrainer.labels_root = labels_root

    train_args = dict(
        data=str(data_yaml),
        epochs=int(cfg["epochs"]),
        imgsz=imgsz,
        batch=int(cfg["batch"]),
        device=str(cfg["device"]),
        workers=int(cfg["workers"]),
        optimizer=str(cfg["optimizer"]),
        lr0=float(cfg["lr0"]),
        lrf=float(cfg["lrf"]),
        warmup_epochs=float(cfg["warmup_epochs"]),
        patience=int(cfg["patience"]),
        seed=int(cfg["seed"]),
        deterministic=bool(cfg["deterministic"]),
        cache=cfg["cache"],
        cos_lr=bool(cfg["cos_lr"]),
        close_mosaic=int(cfg["close_mosaic"]),
        translate=float(cfg["translate"]),
        scale=float(cfg["scale"]),
        fliplr=float(cfg["fliplr"]),
        flipud=float(cfg["flipud"]),
        hsv_h=float(cfg["hsv_h"]),
        hsv_s=float(cfg["hsv_s"]),
        hsv_v=float(cfg["hsv_v"]),
        erasing=float(cfg["erasing"]),
        project=str(project),
        name=str(cfg["name"]),
        exist_ok=bool(cfg.get("exist_ok", False)),
        plots=bool(cfg.get("plots", True)),
        val=True,
    )
    # forward any unknown key=value straight to ultralytics (resume, save_period, ...)
    for k, v in cfg.items():
        if k not in train_args and k not in {
            "model",
            "data",
            "labels_root",
            "dist_lambda",
            "dist_huber_delta",
            "project",
            "name",
        }:
            train_args[k] = v

    YOLO(str(model_yaml)).train(trainer=DistTrainer, **train_args)


if __name__ == "__main__":
    main()
