#!/home/kang/miniforge3/envs/yolo/bin/python
"""Generate ultralytics data yamls from configs/metdist_dataset.yaml.

The dataset location lives in exactly one file.  This tool expands it into the
absolute paths ultralytics expects, so moving the dataset means editing one line
and re-running this script:

    tools/data/make_data_yaml.py               # -> configs/metdist_data.yaml
    tools/data/make_data_yaml.py --smoke       # + configs/metdist_smoke_data.yaml
                                               #   + datasets/metdist_smoke/{train,val}.txt

Nothing is written into the dataset itself.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

import yaml

HERE = Path(__file__).resolve()
WS = HERE.parents[2]                      # .../hzh_workspace
DATASET_CFG = WS / "configs" / "metdist_dataset.yaml"


def load_dataset_cfg(path: Path) -> dict:
    cfg = yaml.safe_load(path.read_text()) or {}
    if not cfg.get("dataset_root"):
        raise SystemExit(f"{path}: missing dataset_root")
    cfg.setdefault("train_images", "images/train")
    cfg.setdefault("val_images", "images/val")
    cfg.setdefault("labels_dist", "labels_dist")
    if not cfg.get("names"):
        raise SystemExit(f"{path}: missing names")
    return cfg


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset-config", default=str(DATASET_CFG))
    ap.add_argument("--out", default=str(WS / "configs" / "metdist_data.yaml"))
    ap.add_argument("--smoke", action="store_true", help="also write the 20+10 image smoke lists")
    ap.add_argument("--smoke-train", type=int, default=20)
    ap.add_argument("--smoke-val", type=int, default=10)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    cfg_path = Path(args.dataset_config)
    cfg = load_dataset_cfg(cfg_path)
    root = Path(cfg["dataset_root"])

    names = {int(k): str(v) for k, v in cfg["names"].items()}
    data = {
        "path": str(root),
        "train": cfg["train_images"],
        "val": cfg["val_images"],
        "names": names,
        "nc": len(names),
    }
    header = (
        "# GENERATED by tools/data/make_data_yaml.py from configs/metdist_dataset.yaml\n"
        f"# dataset_root: {root}\n"
        f"# labels (6 columns) are read by libs/detdist/data.py from "
        f"{root / cfg['labels_dist']}\n"
        "# do not edit by hand; edit configs/metdist_dataset.yaml and re-run the generator\n"
    )
    out = Path(args.out)
    out.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True))
    print(f"[data] wrote {out}")
    print(f"[data] path={root}  train={cfg['train_images']}  val={cfg['val_images']}  nc={len(names)}")
    print(f"[data] labels_dist={root / cfg['labels_dist']}")

    if not args.smoke:
        return
    rng = random.Random(args.seed)
    smoke_dir = WS / "datasets" / "metdist_smoke"
    smoke_dir.mkdir(parents=True, exist_ok=True)
    exts = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}
    lists = {}
    for split, key, n in (("train", "train_images", args.smoke_train), ("val", "val_images", args.smoke_val)):
        imgs = sorted(p for p in (root / cfg[key]).rglob("*") if p.suffix.lower() in exts)
        if not imgs:
            raise SystemExit(f"no images under {root / cfg[key]}")
        picked = imgs if len(imgs) <= n else rng.sample(imgs, n)
        lst = smoke_dir / f"{split}.txt"
        lst.write_text("\n".join(str(p) for p in sorted(picked)) + "\n")
        lists[split] = str(lst)
        print(f"[smoke] {lst}: {len(picked)} images")
    smoke = {"path": str(root), "train": lists["train"], "val": lists["val"], "names": names, "nc": len(names)}
    smoke_yaml = WS / "configs" / "metdist_smoke_data.yaml"
    smoke_yaml.write_text(
        "# GENERATED by tools/data/make_data_yaml.py --smoke\n"
        + yaml.safe_dump(smoke, sort_keys=False, allow_unicode=True)
    )
    print(f"[smoke] wrote {smoke_yaml}")


if __name__ == "__main__":
    main()
